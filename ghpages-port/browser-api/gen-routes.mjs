// Generates routes.generated.ts: every EmDash API route file, lazily imported.
// node gen-routes.mjs [exclude-regex]
import { readdirSync, statSync, writeFileSync } from "node:fs";
import { join, relative } from "node:path";

const root = "packages/core/src/astro/routes/api";
const exclude = process.argv[2] ? new RegExp(process.argv[2]) : null;
const files = [];
(function walk(d) {
	for (const n of readdirSync(d)) {
		const p = join(d, n);
		if (statSync(p).isDirectory()) walk(p);
		else if (n.endsWith(".ts") && !n.endsWith(".d.ts")) files.push(p);
	}
})(root);

const entries = [];
for (const f of files.sort()) {
	const rel = relative(root, f).replace(/\.ts$/, "");
	if (exclude?.test(rel)) continue;
	const segs = rel.split("/");
	if (segs.at(-1) === "index") segs.pop();
	const pattern = "/" + segs.map((s) => (s.startsWith("[...") ? "*" + s.slice(4, -1) : s.startsWith("[") ? ":" + s.slice(1, -1) : s)).join("/");
	entries.push(`\t[${JSON.stringify(pattern)}, () => import(${JSON.stringify("../../" + f)})],`);
}
writeFileSync("ghpages-port/browser-api/routes.generated.ts",
	`// generated by gen-routes.mjs\nexport const routeModules: Array<[string, () => Promise<any>]> = [\n${entries.join("\n")}\n];\n`);
console.log(entries.length, "routes");
